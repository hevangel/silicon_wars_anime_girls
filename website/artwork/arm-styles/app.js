/* Arm in Every Style — course atlas
   No framework. Renders one lesson at a time from window.STUDY. */

(function () {
  "use strict";

  const DATA = window.STUDY;
  const lessons = DATA.lessons;
  const byId = new Map(lessons.map((l) => [l.id, l]));
  const READ_KEY = "arm-atlas-read";

  const el = (tag, attrs, ...kids) => {
    const n = document.createElement(tag);
    if (attrs) {
      for (const [k, v] of Object.entries(attrs)) {
        if (v === undefined || v === null || v === false) continue;
        if (k === "class") n.className = v;
        else if (k === "html") n.innerHTML = v;
        else if (k.startsWith("on")) n.addEventListener(k.slice(2), v);
        else n.setAttribute(k, v);
      }
    }
    for (const kid of kids.flat()) {
      if (kid === null || kid === undefined || kid === false) continue;
      n.appendChild(typeof kid === "string" ? document.createTextNode(kid) : kid);
    }
    return n;
  };

  /* ------------------------------------------------------------- storage --- */
  const readSet = () => {
    try { return new Set(JSON.parse(localStorage.getItem(READ_KEY) || "[]")); }
    catch (_) { return new Set(); }
  };
  const markRead = (id) => {
    const s = readSet(); s.add(id);
    try { localStorage.setItem(READ_KEY, JSON.stringify([...s])); } catch (_) {}
  };

  /* ---------------------------------------------------------------- rail --- */
  function buildRail() {
    const co = DATA.coverage;
    const rail = document.getElementById("rail");

    rail.appendChild(el("p", { class: "brand" }, "Silicon Wars · Art direction"));
    rail.appendChild(el("h1", { class: "brand-title" }, DATA.title));
    rail.appendChild(el("p", { class: "brand-sub" },
      DATA.subtitle.split("—")[0].trim(), el("br"),
      el("b", null, "All images generated by Seedream")));

    rail.appendChild(el("div", { class: "meter" },
      el("div", { class: "meter-bar" }, el("span", { style: `width:${co.percent}%` })),
      el("div", { class: "meter-label" },
        el("span", null, "plates rendered"),
        el("span", null, el("b", null, `${co.rendered}/${co.total}`), ` · ${co.percent}%`))));

    rail.appendChild(el("p", { class: "nav-h" }, "Lessons"));
    const ol = el("ol", { class: "lessons", id: "lessonList" });
    for (const l of lessons) {
      ol.appendChild(el("li", { "data-id": l.id },
        el("a", { href: `#${l.id}` },
          el("span", { class: "num" }, l.number),
          el("span", { class: "label" }, l.title),
          el("span", { class: "tick" }, "●"))));
    }
    rail.appendChild(ol);

    rail.appendChild(el("p", { class: "rail-foot" },
      el("b", null, "Method."), " One character, one pose, 105 styles. ",
      "Prompts and hashes are recorded beside every render in ",
      el("code", null, "art/style-study/"), "."));
    rail.appendChild(el("p", { class: "rail-foot" },
      el("b", null, "Images."), " All 219 plates are generated with Seedream from the ",
      "Arm character sheet; this page shows the plates finished so far."));
  }

  function syncRail(activeId) {
    const read = readSet();
    document.querySelectorAll("#lessonList li").forEach((li) => {
      const id = li.getAttribute("data-id");
      li.classList.toggle("active", id === activeId);
      li.classList.toggle("done", read.has(id));
    });
  }

  /* ------------------------------------------------------------ lightbox --- */
  let box, boxImg, boxCap, current = [];

  function openBox(list, index) {
    current = list;
    paint(index);
    box.hidden = false;
    document.body.style.overflow = "hidden";
  }
  function paint(index) {
    const item = current[index];
    if (!item) return;
    boxImg.src = item.src;
    boxImg.alt = item.alt;
    boxCap.innerHTML = `<b>${item.style}</b> — ${item.cap}. Generated with Seedream.`;
    box.dataset.index = String(index);
  }
  function closeBox() {
    box.hidden = true;
    document.body.style.overflow = "";
  }

  function ensureBox() {
    if (box) return;
    boxImg = el("img", { alt: "" });
    boxCap = el("figcaption");
    box = el("div", { class: "lightbox", hidden: "hidden", role: "dialog",
      "aria-modal": "true", "aria-label": "Plate viewer" },
      el("button", { class: "close", "aria-label": "Close", onclick: closeBox }, "×"),
      el("button", { class: "nav prev", "aria-label": "Previous", onclick: () => step(-1) }, "‹"),
      el("button", { class: "nav next", "aria-label": "Next", onclick: () => step(1) }, "›"),
      el("figure", null, boxImg, boxCap));
    box.addEventListener("click", (e) => { if (e.target === box) closeBox(); });
    document.body.appendChild(box);
  }
  function step(d) {
    const n = current.length;
    const i = (Number(box.dataset.index) + d + n) % n;
    paint(i);
  }

  /* -------------------------------------------------------------- a plate --- */
  function plateFigure(style, plate, gallery) {
    if (plate.status !== "rendered") {
      return el("figure", { class: "plate" },
        el("div", { class: "slot" }, `v${plate.variant}`, el("br"), "plate pending"),
        el("div", { class: "cap" },
          el("b", null, `v${plate.variant}`), " · ", plate.axis));
    }
    const item = {
      src: plate.src,
      alt: `${style.label}, version ${plate.variant}: ${plate.axis}`,
      style: style.label,
      cap: `v${plate.variant} · ${plate.axis}`,
    };
    gallery.push(item);
    const idx = gallery.length - 1;
    return el("figure", { class: "plate" },
      el("button", { type: "button", "aria-label": `Enlarge ${style.label} v${plate.variant}`,
        onclick: () => openBox(gallery, idx) },
        el("img", { src: plate.src, width: plate.w, height: plate.h,
          loading: "lazy", alt: item.alt })),
      el("div", { class: "cap" }, el("b", null, `v${plate.variant}`), " · ", plate.axis));
  }

  function styleBlock(style, ix) {
    const gallery = [];
    const done = style.plates.filter((p) => p.status === "rendered").length;
    const modeChip = style.mode === "pose"
      ? el("span", { class: "chip pose" }, "pose held")
      : el("span", { class: "chip lang" }, "language reinterpreted");

    const block = el("article", { class: "style", id: `style-${style.slug}` },
      el("div", { class: "style-head" },
        el("span", { class: "style-ix" }, String(ix).padStart(2, "0")),
        el("h3", null, style.label),
        modeChip,
        el("span", { class: "chip" }, done ? `${done} plate${done > 1 ? "s" : ""}` : "pending")),
      el("p", { class: "medium" }, style.medium),
      el("div", { class: "plates" }, style.plates.map((p) => plateFigure(style, p, gallery))),
      el("p", { class: "style-links" },
        el("span", null, "Go deeper:"),
        style.links.map((l) => el("a", { href: l.url, target: "_blank",
          rel: "noopener noreferrer" }, `${l.label}`))));

    if (!done) block.classList.add("is-pending");
    return block;
  }

  /* --------------------------------------------------------------- lesson --- */
  function render(id, push) {
    const lesson = byId.get(id) || lessons[0];
    const page = document.getElementById("page");
    page.innerHTML = "";

    page.appendChild(el("p", { class: "kicker" }, `Lesson ${lesson.number} · ${lesson.kicker}`));
    page.appendChild(el("h1", null, el("span", { class: "n" }, lesson.number), lesson.title));
    page.appendChild(el("p", { class: "lead" }, lesson.lead));

    page.appendChild(el("div", { class: "meta-row" },
      el("span", null, el("b", null, String(lesson.styles.length)), " styles"),
      el("span", null, el("b", null, `${lesson.plates_done}/${lesson.plates_total}`), " plates here"),
      el("span", null, el("b", null, DATA.coverage.percent + "%"), " of the atlas rendered"),
      el("span", null, "subject: ", el("b", null, "Arm"))));

    if (lesson.body.length) {
      page.appendChild(el("div", { class: "prose" }, lesson.body.map((p) => el("p", null, p))));
    }

    if (lesson.axes) {
      page.appendChild(el("div", { class: "axes" },
        lesson.axes.map(([name, text]) =>
          el("div", { class: "axis" }, el("h4", null, name), el("p", null, text)))));
    }

    if (lesson.styles.length === 0) {
      page.appendChild(el("figure", { class: "identity" },
        el("img", { src: DATA.identity, alt: "Arm character sheet: front, three-quarter, side and back views with three expressions" }),
        el("figcaption", null,
          "The identity reference used for every plate: Arm’s turnaround and expression ",
          "sheet. Costume, hair, ribbon and boots are fixed; only the medium changes. ",
          "Generated with Seedream.")));
    } else {
      page.appendChild(el("section", { class: "styles" },
        el("h2", null, "The plates"),
        el("p", null, "Each style appears up to four times. Click any plate to enlarge; ",
          "use ← → inside the viewer."),
        lesson.styles.map((s, i) => styleBlock(s, i + 1))));
    }

    if (lesson.takeaway) {
      page.appendChild(el("div", { class: "takeaway" },
        el("span", null, "Take this away"), el("p", null, lesson.takeaway)));
    }

    page.appendChild(el("div", { class: "resources" },
      el("h4", null, "Read further"),
      el("ul", null, lesson.links.map((l) =>
        el("li", null, el("a", { href: l.url, target: "_blank",
          rel: "noopener noreferrer" }, l.label))))));

    const i = lessons.indexOf(lesson);
    const prev = lessons[i - 1], next = lessons[i + 1];
    page.appendChild(el("nav", { class: "pager" },
      prev ? el("a", { href: `#${prev.id}` }, el("span", { class: "dir" }, "Previous"),
        `${prev.number} · ${prev.title}`) : el("span"),
      next ? el("a", { href: `#${next.id}`, style: "text-align:right" },
        el("span", { class: "dir" }, "Next"), `${next.number} · ${next.title}`) : el("span")));

    page.appendChild(el("footer", { class: "colophon" },
      el("b", null, "Arm in Every Style"), " — ", String(lessons.length),
      " lessons, 105 styles, ", String(DATA.coverage.total), " plates planned, ",
      String(DATA.coverage.rendered), " rendered. ",
      "Every image on this page was generated with ", el("b", null, "Seedream"),
      " from the Arm character sheet; each plate keeps its prompt and render hash in ",
      el("code", null, "art/style-study/renders/"), ". ",
      "Reference links go to Wikipedia and Smarthistory; both open in a new tab."));

    markRead(lesson.id);
    syncRail(lesson.id);
    document.title = `${lesson.title} · Arm in Every Style`;
    if (push) history.replaceState(null, "", `#${lesson.id}`);
    window.scrollTo({ top: 0, behavior: "instant" in window ? "instant" : "auto" });
  }

  /* ----------------------------------------------------------------- boot --- */
  function boot() {
    ensureBox();
    buildRail();
    const initial = (location.hash || "#l00").slice(1);
    render(initial, false);

    window.addEventListener("hashchange", () => {
      const id = (location.hash || "#l00").slice(1);
      if (byId.has(id)) render(id, false);
    });

    document.addEventListener("keydown", (e) => {
      if (!box.hidden) {
        if (e.key === "Escape") closeBox();
        if (e.key === "ArrowRight") step(1);
        if (e.key === "ArrowLeft") step(-1);
        return;
      }
      if (e.target.closest("input, textarea")) return;
      const id = (location.hash || "#l00").slice(1);
      const i = lessons.findIndex((l) => l.id === id);
      if (e.key === "ArrowRight" && lessons[i + 1]) location.hash = lessons[i + 1].id;
      if (e.key === "ArrowLeft" && lessons[i - 1]) location.hash = lessons[i - 1].id;
    });
  }

  document.addEventListener("DOMContentLoaded", boot);
})();
